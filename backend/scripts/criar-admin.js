import bcrypt from 'bcryptjs';
import { carregarAmbiente } from '../config/ambiente.js';
import { criarPool } from '../config/database.js';
carregarAmbiente('.env');
const { ADMIN_NOME, ADMIN_EMAIL, ADMIN_SENHA } = process.env;
if (!ADMIN_NOME || !ADMIN_EMAIL || !ADMIN_SENHA || ADMIN_SENHA.length < 8) throw new Error('Defina ADMIN_NOME, ADMIN_EMAIL e ADMIN_SENHA (mínimo 8 caracteres) no .env antes de executar.');
const hash = await bcrypt.hash(ADMIN_SENHA, 12);
await criarPool().query('INSERT INTO usuarios (nome, email, senha_hash, perfil) VALUES (?, ?, ?, \'Administrador\')', [ADMIN_NOME, ADMIN_EMAIL.toLowerCase(), hash]);
console.log('Administrador criado com sucesso. Remova ADMIN_SENHA do .env após o uso.');
process.exit(0);
